-- LA CREACION DE SECUENCIAS 
-- LAS SECUENCIAS SON OBJETOS QUE NOS PERMITEN GENERAR VALORES DE NUEMEROS ENTEROS 
--EN FORMA CONSECUTIVA CON UN INCREMENTO DETERMINADO
--NOA VA APERMITIR DETERMINAR LA CANTIDAD DE INCREMENTO
--SE UTILIZAN PARA GENERAR LAS LLAVES PRIMARIAS Y DE ESTA FORMA LOGRAMOS AUN 
--MAS QUE LOS VALORES NO SE REPITAN 
--VAMOS ACREAR IUNA CESUENSIA PARA UNA TABLA QUE YA TIENE REGISTROS INCERTADOS 
--CREA UNA SECIENCIA CON VALORES DEFINIDOS 
SELECT * FROM ALUMNO;

CREATE SEQUENCE ALUMNO_SEQ --NOMBRE DE LA SECUENCIA
START WITH 5 --DESDE QUE VALOR INICIA
INCREMENT BY 1 -- EN CUANTO EN CUANTO INCREMENTA
MAXVALUE 999 --VALOR MAXIMO
MINVALUE 1 --VALOR MINIMO
NOCYCLE; --SI QUEREMOS QUEREMOS QUE SE SICLE SERIA CON CYCLE

-- EJEMPLO DE CREAR UNA SECUENCIA CON VALORES DEFAULT
--LA CUAL ES UTIL PARA TABLAS QUE NO TIENE DATOS AGREGADOS
