COMMIT;

--VAMOS A CREAR EL DISPARADOR O DE TRIGGERS
--ESTOS SON UN TIPO DE PROCEDIMIENTO ALMACENADO QUE DESENCADENA UN EVENTO 
--EN ESTE CASO LO UTILIZAREMOS PARA INCERTAR LAS LLAVES PRIMARIAS 
--EJEMPO. CREACION DE L DISPARADOR PARA INCERTAR LOS IDS EN LA TABLA ALUMNO

CREATE OR REPLACE TRIGGER INSERT_ALUMNO -- NOMBRE DEL TRIGGER
BEFORE INSERT ON ALUMNO FOR EACH ROW BEGIN -- DONDE ACTUARA
SELECT ALUMNO_SEQ.NEXTVAL INTO:NEW.ALUMNO_ID FROM DUAL; -- QUE HACE TOMA EL VALOR DE LA SECUENCIA PARA INCERTARLO PARA TOMAR EL VALOR DEL ID
END;

